let passed = 0

async function scenario(title, execute) {
  const page = await browser.newPage({ viewport: { width: 1280, height: 800 } })
  page.setDefaultTimeout(12000)
  try {
    await page.goto(origin)
    await execute(page)
    ++passed
    console.log('PASS ' + title)
  } catch (error) {
    await page.screenshot({ path: '../var/browser-failure.png', fullPage: true }).catch(() => {})
    console.error('FAIL ' + title)
    throw error
  } finally {
    await page.close()
  }
}

